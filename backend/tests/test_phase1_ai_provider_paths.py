    """_complete_with_active_provider must dispatch through complete_text for any provider."""

    @pytest.mark.parametrize("provider,model", PROVIDERS)
    async def test_dispatches_for_all_providers(self, provider, model):
        service = AIService()
        db = MagicMock(spec=AsyncSession)

