        fake_cred = ActiveCredential(id=1, provider=provider, model_id=model, api_key="testkey12345")

        async def fake_get_cred(db, user_id, model_name=None):
            return fake_cred

        # Mock DB execute to return thread, then messages
        call_count = [0]
        def make_execute_side_effect():
            def side_effect(*args, **kwargs):
                call_count[0] += 1
                mock_result = MagicMock()
                if call_count[0] == 1:
                    # thread fetch
                    mock_result.scalar_one_or_none = MagicMock(return_value=mock_thread)
                elif call_count[0] == 2:
                    # user message add (commit call is separate)
                    mock_result.scalar_one_or_none = MagicMock(return_value=None)
                else:
                    # recent messages
                    mock_result.scalars.return_value.all = MagicMock(return_value=[])
                return mock_result
            return side_effect

        db.execute = AsyncMock(side_effect=make_execute_side_effect())
        db.add = MagicMock()
        db.commit = AsyncMock()

        with (
            patch.object(service, "_get_active_credential", new=AsyncMock(return_value=fake_cred)),
            patch.object(service, "_fetch_project", new=AsyncMock(return_value=mock_project)),
            patch.object(service, "_fetch_latest_analysis", new=AsyncMock(return_value=None)),
            patch.object(service, "_get_template_prompt", new=AsyncMock(return_value=None)),
            patch("app.services.ai_doc_service.complete_text", return_value=f"Response from {provider}") as mock_complete,
        ):
            gen = await service.stream_chat(
                thread_id=1,
                user_message="hello",
                db=db,
                user_id=1,
            )
            chunks = []
            async for chunk in gen:
                chunks.append(chunk)

        full = "".join(chunks)
        assert f"Response from {provider}" in full
        mock_complete.assert_called_once()
        call_kwargs = mock_complete.call_args
        assert call_kwargs.args[2] == provider  # provider arg


